# while-loop: a while loop keeps running as long as its condition is true, python check the condtion before every iteration - the moment it becomes false, the loops stops.

# while condition:
    # this block runs repeatedly until condition is false.

count = 1

while count <= 5:
    print(f"Count is {count}")
    count += 1

# Output:
# Count is 1
# Count is 2
# Count is 3
# Count is 4
# Count is 5