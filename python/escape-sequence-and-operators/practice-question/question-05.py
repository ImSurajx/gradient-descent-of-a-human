"""
question-04: take a number as input. print the result of that number raised to the power of 3 using **. also print what // 7 and %7 give for the same number
"""
num = int(input("enter a number: "))
print(f"{num} raised to 3 is: {num**3}")
print(f"{num} floor divide by 7 is: {num//7}")
print(f"{num} moduls by 7 is: {num%7}")
